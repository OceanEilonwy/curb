use std::fs;
use std::net::{IpAddr, SocketAddr};
use std::os::unix::io::AsRawFd;
use std::path::Path;

use curb_core::adaptors::DnsManager;

use crate::CURB_FW_MARK;

/// Linux DNS adaptor: discovers real upstream resolvers across `systemd-resolved`,
/// `NetworkManager`, and `/etc/resolv.conf`, and marks Curb's own upstream sockets
/// with `SO_MARK` so they bypass transparent DNS interception.
#[derive(Debug, Default, Clone, Copy)]
pub struct LinuxDnsManager;

impl DnsManager for LinuxDnsManager {
    fn discover_upstreams(&self) -> Vec<SocketAddr> {
        discover_linux_upstream_dns()
    }

    fn restore_clean(&self, _data_dir: &Path) -> Result<(), String> {
        // Linux uses transparent nftables NAT redirect so `/etc/resolv.conf` is never mutated.
        Ok(())
    }
}

/// Marks a socket with `SO_MARK = CURB_FW_MARK` (`0x43555242`).
pub fn set_curb_fw_mark<F: AsRawFd>(fd: &F) -> std::io::Result<()> {
    let mark = CURB_FW_MARK;
    let ret = unsafe {
        libc::setsockopt(
            fd.as_raw_fd(),
            libc::SOL_SOCKET,
            libc::SO_MARK,
            (&mark as *const u32).cast::<libc::c_void>(),
            std::mem::size_of::<u32>() as libc::socklen_t,
        )
    };
    if ret == 0 {
        Ok(())
    } else {
        Err(std::io::Error::last_os_error())
    }
}

pub fn discover_linux_upstream_dns() -> Vec<SocketAddr> {
    let mut out = Vec::new();
    for path in [
        "/run/systemd/resolve/resolv.conf",
        "/run/NetworkManager/no-stub-resolv.conf",
        "/run/NetworkManager/resolv.conf",
        "/run/resolvconf/resolv.conf",
        "/var/run/connman/resolv.conf",
        "/etc/resolv.conf",
    ] {
        if let Ok(content) = fs::read_to_string(path) {
            for addr in parse_resolv_conf(&content) {
                if !out.contains(&addr) {
                    out.push(addr);
                }
            }
        }
    }
    out
}

pub fn parse_resolv_conf(content: &str) -> Vec<SocketAddr> {
    let mut out = Vec::new();
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with(';') {
            continue;
        }
        let mut parts = trimmed.split_whitespace();
        if parts.next() != Some("nameserver") {
            continue;
        }
        let Some(raw_ip) = parts.next() else {
            continue;
        };
        let clean_ip = raw_ip.split('%').next().unwrap_or(raw_ip);
        let Ok(ip) = clean_ip.parse::<IpAddr>() else {
            continue;
        };
        if ip.is_loopback() || ip.is_unspecified() {
            continue;
        }
        let sock = SocketAddr::new(ip, 53);
        if !out.contains(&sock) {
            out.push(sock);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_resolv_conf_and_filters_loopback_stubs() {
        let sample = r#"
# Generated by systemd-resolved
nameserver 127.0.0.53
nameserver ::1
nameserver 192.168.1.1
nameserver 1.1.1.1
nameserver 2606:4700:4700::1111
nameserver 192.168.1.1
"#;
        let parsed = parse_resolv_conf(sample);
        assert_eq!(
            parsed,
            vec![
                "192.168.1.1:53".parse().unwrap(),
                "1.1.1.1:53".parse().unwrap(),
                "[2606:4700:4700::1111]:53".parse().unwrap(),
            ]
        );
    }
}
