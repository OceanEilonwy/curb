use std::fs;
use std::net::{IpAddr, SocketAddr};
use std::os::unix::io::AsRawFd;
use std::path::Path;

use curb_core::adaptors::DnsManager;

use crate::CURB_FW_MARK;

/// Linux DNS adaptor: discovers real upstream resolvers across `systemd-resolved`,
/// `NetworkManager`, and `/etc/resolv.conf`, and marks Curb's own upstream sockets
/// with `SO_MARK` so they bypass transparent DNS interception.
#[derive(Debug, Default, Clone, Copy)]
pub struct LinuxDnsManager;

impl DnsManager for LinuxDnsManager {
    fn discover_upstreams(&self) -> Vec<SocketAddr> {
        discover_linux_upstream_dns()
    }

    fn restore_clean(&self, _data_dir: &Path) -> Result<(), String> {
        // Linux uses transparent nftables NAT redirect so `/etc/resolv.conf` is never mutated.
        Ok(())
    }
}

/// Marks a socket with `SO_MARK = CURB_FW_MARK` (`0x43555242`).
pub fn set_curb_fw_mark<F: AsRawFd>(fd: &F) -> std::io::Result<()> {
    let mark = CURB_FW_MARK;
    let ret = unsafe {
        libc::setsockopt(
            fd.as_raw_fd(),
            libc::SOL_SOCKET,
            libc::SO_MARK,
            (&mark as *const u32).cast::<libc::c_void>(),
            std::mem::size_of::<u32>() as libc::socklen_t,
        )
    };
    if ret == 0 {
        Ok(())
    } else {
        Err(std::io::Error::last_os_error())
    }
}

pub fn discover_linux_upstream_dns() -> Vec<SocketAddr> {
    discover_from_paths(&[
        "/run/systemd/resolve/resolv.conf",
        "/run/NetworkManager/no-stub-resolv.conf",
        "/run/NetworkManager/resolv.conf",
        "/run/resolvconf/resolv.conf",
        "/var/run/connman/resolv.conf",
        "/etc/resolv.conf",
    ])
}

fn discover_from_paths(paths: &[&str]) -> Vec<SocketAddr> {
    // Prefer the first active resolver configuration that yields usable non-loopback
    // upstream servers so stale files from inactive network managers do not pollute
    // the upstream race list.
    for path in paths {
        if let Ok(content) = fs::read_to_string(path) {
            let found = parse_resolv_conf(&content);
            if !found.is_empty() {
                return found;
            }
        }
    }
    Vec::new()
}

/// Best-effort flush of local Linux DNS caches (e.g. `systemd-resolved`) when Curb
/// enters enforcing mode so apps using `nss-resolve` do not receive stale cached IPs
/// that Curb's `DnsCache` has not yet observed.
pub fn flush_linux_dns_caches() {
    let _ = std::process::Command::new("resolvectl")
        .arg("flush-caches")
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status();
}

pub fn parse_resolv_conf(content: &str) -> Vec<SocketAddr> {
    let mut out = Vec::new();
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with(';') {
            continue;
        }
        let mut parts = trimmed.split_whitespace();
        if parts.next() != Some("nameserver") {
            continue;
        }
        let Some(raw_ip) = parts.next() else {
            continue;
        };
        // Skip scoped/link-local IPv6 addresses (e.g. `fe80::1%eth0`): `SocketAddr`
        // without a kernel scope_id fails `connect()` with EINVAL.
        let clean_ip = raw_ip.split('%').next().unwrap_or(raw_ip);
        let Ok(ip) = clean_ip.parse::<IpAddr>() else {
            continue;
        };
        if ip.is_loopback() || ip.is_unspecified() {
            continue;
        }
        if let IpAddr::V6(v6) = ip {
            if (v6.segments()[0] & 0xffc0) == 0xfe80 {
                continue;
            }
        }
        let sock = SocketAddr::new(ip, 53);
        if !out.contains(&sock) {
            out.push(sock);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_resolv_conf_and_filters_loopback_and_link_local() {
        let sample = r#"
# Generated by systemd-resolved
nameserver 127.0.0.53
nameserver ::1
nameserver fe80::1%eth0
nameserver fe80::abcd
nameserver 192.168.1.1
nameserver 1.1.1.1
nameserver 2606:4700:4700::1111
nameserver 192.168.1.1
"#;
        let parsed = parse_resolv_conf(sample);
        assert_eq!(
            parsed,
            vec![
                "192.168.1.1:53".parse().unwrap(),
                "1.1.1.1:53".parse().unwrap(),
                "[2606:4700:4700::1111]:53".parse().unwrap(),
            ]
        );
    }

    #[test]
    fn discover_prefers_first_active_resolv_conf() {
        let dir = std::env::temp_dir().join(format!("curb_dns_disc_{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        let p1 = dir.join("resolved.conf");
        let p2 = dir.join("stale_nm.conf");
        fs::write(&p1, "nameserver 10.0.0.1\n").unwrap();
        fs::write(&p2, "nameserver 192.168.99.1\n").unwrap();

        let p1_s = p1.to_string_lossy().to_string();
        let p2_s = p2.to_string_lossy().to_string();
        let found = discover_from_paths(&[p1_s.as_str(), p2_s.as_str()]);
        assert_eq!(found, vec!["10.0.0.1:53".parse().unwrap()]);

        let _ = fs::remove_dir_all(&dir);
    }
}
